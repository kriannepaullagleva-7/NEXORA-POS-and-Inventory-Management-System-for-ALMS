-- =============================================================================
-- MIGRATION 002 — tiered delivery pricing, laundry weight limits, and the flag
--                 that decides which water products are charged delivery.
--
-- Safe to run on a database that already has these objects: every statement is
-- guarded, so re-running it changes nothing. Adds no destructive step and
-- touches no existing row.
--
-- Run in: Supabase Dashboard → SQL Editor → New query → Run
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Delivery is tiered, not per-gallon
--
--    The tiers give the TOTAL charge for exactly that many refills, so four
--    refills is 155, not 4 x 35. Rows are editable from
--    Products and Services → Delivery Pricing.
-- -----------------------------------------------------------------------------
create table if not exists public.delivery_pricing (
  id        bigint generated by default as identity primary key,
  quantity  integer not null unique check (quantity > 0),
  price     numeric not null check (price >= 0),
  is_active boolean not null default true
);

insert into public.delivery_pricing (quantity, price, is_active) values
  (1, 35, true), (2, 70, true), (3, 100, true),
  (4, 155, true), (5, 170, true), (6, 200, true)
on conflict (quantity) do nothing;

-- -----------------------------------------------------------------------------
-- 2. Laundry services carry a weight ceiling per load
-- -----------------------------------------------------------------------------
alter table public.laundry_services
  add column if not exists max_kg numeric;

update public.laundry_services set max_kg = 8 where id = 'SVC-001' and max_kg is null;
update public.laundry_services set max_kg = 8 where id = 'SVC-002' and max_kg is null;
update public.laundry_services set max_kg = 4 where id = 'SVC-003' and max_kg is null;

-- -----------------------------------------------------------------------------
-- 3. Only refills count toward the delivery tiers
--
--    Caps and empty containers are sold alongside refills but must not inflate
--    the delivery fee.
-- -----------------------------------------------------------------------------
alter table public.water_products
  add column if not exists counts_for_delivery boolean not null default false;

update public.water_products
   set counts_for_delivery = true
 where category = 'Refill'
   and counts_for_delivery = false;

-- -----------------------------------------------------------------------------
-- 4. Row Level Security — only an admin may change prices
--
--    Migration 001 created delivery_pricing alongside the operational tables,
--    which let any signed-in employee edit it. Delivery prices are configuration,
--    not day-to-day data, and the screen that edits them (Products and Services)
--    is admin-only, so the policies are replaced here with a read-for-all,
--    write-for-admin set.
--
--    Postgres ORs permissive policies together, so the old permissive ones have
--    to be dropped rather than merely added to: leaving them in place would keep
--    the admin-only rule switched off. Dropping a policy removes no data.
-- -----------------------------------------------------------------------------
alter table public.delivery_pricing enable row level security;

drop policy if exists alms_read   on public.delivery_pricing;
drop policy if exists alms_write  on public.delivery_pricing;
drop policy if exists alms_update on public.delivery_pricing;
drop policy if exists alms_delete on public.delivery_pricing;

drop policy if exists delivery_pricing_select on public.delivery_pricing;
drop policy if exists delivery_pricing_insert on public.delivery_pricing;
drop policy if exists delivery_pricing_update on public.delivery_pricing;
drop policy if exists delivery_pricing_delete on public.delivery_pricing;

create policy delivery_pricing_select on public.delivery_pricing
  for select to authenticated using (true);

create policy delivery_pricing_insert on public.delivery_pricing
  for insert to authenticated with check (public.is_admin());

create policy delivery_pricing_update on public.delivery_pricing
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy delivery_pricing_delete on public.delivery_pricing
  for delete to authenticated using (public.is_admin());

grant select, insert, update, delete on public.delivery_pricing to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- -----------------------------------------------------------------------------
-- 5. Verification
-- -----------------------------------------------------------------------------
select 'delivery tiers'               as item, count(*)::text as value from public.delivery_pricing
union all select 'services with max_kg',     count(*)::text from public.laundry_services where max_kg is not null
union all select 'products billed delivery', count(*)::text from public.water_products where counts_for_delivery
union all select 'delivery_pricing policies (expect 4)',
                 count(*)::text from pg_policies where schemaname = 'public' and tablename = 'delivery_pricing';
